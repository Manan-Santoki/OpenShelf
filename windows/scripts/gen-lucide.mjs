// Generates windows/OpenShelf.Ui/Lucide.g.cs from the official lucide-static package.
//   npm pack lucide-static@1.71.0 && tar xzf lucide-static-1.71.0.tgz
//   node windows/scripts/gen-lucide.mjs <path-to>/package
// The icon list below is the only place that decides which Lucide icons ship in the app.
import fs from 'node:fs';
import path from 'node:path';

const pkgDir = process.argv[2];
if (!pkgDir) { console.error('usage: node gen-lucide.mjs <lucide-static package dir>'); process.exit(1); }
const version = JSON.parse(fs.readFileSync(path.join(pkgDir, 'package.json'), 'utf8')).version;
const nodes = JSON.parse(fs.readFileSync(path.join(pkgDir, 'icon-nodes.json'), 'utf8'));

const names = `
arrow-down arrow-up-right audio-lines external-link highlighter mouse-pointer-2 pencil-line square type badge-check brackets camera chart-pie check chevron-down chevron-left chevron-right chevron-up
circle-arrow-down circle-check circle-dashed circle-question-mark circle-x copy crop ellipsis eye eye-off file file-text
film files folder folder-open gauge grip-vertical hand house image images inbox import info keyboard layout-grid lightbulb
link list lock lock-open map-pin maximize-2 merge minimize-2 minus mouse-pointer-click pause pencil play plus puzzle
qr-code redo-2 refresh-cw rotate-ccw rotate-cw scan-qr-code scan-text scissors settings share sliders-horizontal
square-user-round tag terminal trash triangle-exclamation-point
triangles-centerline-dashed-horizontal triangles-centerline-dashed-vertical undo-2 user-round-x volume-x x
`.split(/\s+/).filter(Boolean);

// Every element becomes its own sub-path, so a leading relative moveto must be read as absolute (SVG does the same at the start of a path).
function absoluteStart(d) {
  const m = /^m\s*(-?[\d.]+)[\s,]*(-?[\d.]+)(.*)$/s.exec(d.trim());
  if (!m) return d;
  const rest = m[3].trim();
  return `M${m[1]} ${m[2]}` + (rest === '' ? '' : /^[a-zA-Z]/.test(rest) ? rest : 'l' + rest);
}
const f = n => String(+n.toFixed(4));
function toPath(tag, a) {
  switch (tag) {
    case 'path': return absoluteStart(a.d);
    case 'line': return `M${a.x1} ${a.y1}L${a.x2} ${a.y2}`;
    case 'polyline': case 'polygon': {
      const p = a.points.trim().split(/[\s,]+/).map(Number), out = [];
      for (let i = 0; i < p.length; i += 2) out.push(`${i ? 'L' : 'M'}${p[i]} ${p[i + 1]}`);
      return out.join('') + (tag === 'polygon' ? 'Z' : '');
    }
    case 'circle': { const cx = +a.cx, cy = +a.cy, r = +a.r; return `M${f(cx - r)} ${f(cy)}a${r} ${r} 0 1 0 ${f(2 * r)} 0a${r} ${r} 0 1 0 ${f(-2 * r)} 0Z`; }
    case 'ellipse': { const cx = +a.cx, cy = +a.cy, rx = +a.rx, ry = +a.ry; return `M${f(cx - rx)} ${f(cy)}a${rx} ${ry} 0 1 0 ${f(2 * rx)} 0a${rx} ${ry} 0 1 0 ${f(-2 * rx)} 0Z`; }
    case 'rect': {
      const x = +a.x || 0, y = +a.y || 0, w = +a.width, h = +a.height;
      const rx = Math.min(+(a.rx ?? a.ry ?? 0), w / 2), ry = Math.min(+(a.ry ?? a.rx ?? 0), h / 2);
      if (!rx && !ry) return `M${x} ${y}H${f(x + w)}V${f(y + h)}H${x}Z`;
      return `M${f(x + rx)} ${y}H${f(x + w - rx)}A${rx} ${ry} 0 0 1 ${f(x + w)} ${f(y + ry)}V${f(y + h - ry)}A${rx} ${ry} 0 0 1 ${f(x + w - rx)} ${f(y + h)}H${f(x + rx)}A${rx} ${ry} 0 0 1 ${x} ${f(y + h - ry)}V${f(y + ry)}A${rx} ${ry} 0 0 1 ${f(x + rx)} ${y}Z`;
    }
    default: throw new Error('unsupported element ' + tag);
  }
}
const pascal = n => n.split('-').map(s => s[0].toUpperCase() + s.slice(1)).join('');
let props = '', table = '';
for (const n of names) {
  if (!nodes[n]) throw new Error('missing icon ' + n);
  const d = nodes[n].map(([tag, a]) => toPath(tag, a)).join(' ');
  props += `    public static Geometry ${pascal(n)} => Get("${n}");\n`;
  table += `        ["${n}"] = "${d}",\n`;
}
const out = `// <auto-generated> by windows/scripts/gen-lucide.mjs from lucide-static ${version} (ISC licence, see LICENSE-lucide.txt). Do not edit.
using System.Windows.Media;

namespace OpenShelf.Ui;

public static partial class Icons
{
    /// <summary>The Lucide release the path data was taken from.</summary>
    public const string LucideVersion = "${version}";

${props}
    static readonly Dictionary<string, string> PathData = new(StringComparer.Ordinal)
    {
${table}    };
}
`;
fs.writeFileSync(new URL('../OpenShelf.Ui/Lucide.g.cs', import.meta.url), out);
console.log(`wrote ${names.length} icons from lucide-static ${version}`);
